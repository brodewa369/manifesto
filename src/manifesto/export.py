"""Exporters: turn a manifesto contract into an enforcer's dialect.

``manifesto export --target agentward`` emits an approximate AgentWard-style
policy YAML skeleton; ``--target denylist`` emits a platform-neutral deny-list
JSON. Both are **deterministic** — the same manifest always produces the same
bytes (keys sorted, no timestamps, stable ordering) so exports are diff-able
and committable.

IMPORTANT: the emitted dialects are **approximations**, not certified schemas
of any vendor. They are reviewable starting points — read the header comment,
adjust to your enforcer's real schema, then enforce. manifesto never talks to
a vendor API.
"""
from __future__ import annotations

import json

from . import __version__

TARGETS = ("agentward", "denylist")

_DISCLAIMER_COMMON = (
    "dialects are approximations, not certified vendor schemas — review before enforcing"
)


def _sorted_grants(manifest):
    grants = manifest.get("grants")
    if not isinstance(grants, dict):
        return []
    return sorted(grants.items(), key=lambda kv: kv[0])


def _sorted_deny(manifest):
    deny = manifest.get("deny")
    if not isinstance(deny, list):
        return []
    return sorted(str(d) for d in deny)


def _sorted_delegations(manifest):
    """Deterministically ordered delegations (by from, then to)."""
    dels = manifest.get("delegations")
    if not isinstance(dels, list):
        return []
    return sorted((d for d in dels if isinstance(d, dict)),
                  key=lambda d: (str(d.get("from", "")), str(d.get("to", ""))))


def _constraints_yaml(value, indent):
    """Render a grant's constraint object as deterministic YAML lines."""
    lines = []
    pad = " " * indent
    if not isinstance(value, dict):
        return lines
    amt = value.get("amount")
    if isinstance(amt, dict):
        lines.append(f"{pad}constraints:")
        lines.append(f"{pad}  amountMax: {amt.get('max')}")
        if amt.get("currency") is not None:
            lines.append(f"{pad}  currency: {amt.get('currency')}")
        if amt.get("window") is not None:
            lines.append(f"{pad}  window: {amt.get('window')}")
    rate = value.get("rate")
    if isinstance(rate, dict):
        if not lines:
            lines.append(f"{pad}constraints:")
        lines.append(f"{pad}  rateMax: {rate.get('max')}")
        if rate.get("window") is not None:
            lines.append(f"{pad}  rateWindow: {rate.get('window')}")
    doms = value.get("to_domains")
    if isinstance(doms, list) and doms:
        if not lines:
            lines.append(f"{pad}constraints:")
        lines.append(f"{pad}  toDomains: [{', '.join(sorted(str(d) for d in doms))}]")
    appr = value.get("approval")
    if appr is not None:
        if not lines:
            lines.append(f"{pad}constraints:")
        lines.append(f"{pad}  requiresApproval: {'true' if appr == 'required' else 'false'}")
    return lines


def export_agentward(manifest, version=__version__) -> str:
    """Approximate AgentWard-style policy YAML skeleton (deterministic)."""
    agent = manifest.get("agent", "unnamed-agent")
    owner = manifest.get("owner", "unknown")
    ttl = manifest.get("ttl")
    out = []
    out.append("# manifesto export -> agentward (APPROXIMATION)")
    out.append(f"# generated by manifesto {version} | {_DISCLAIMER_COMMON}")
    out.append("apiVersion: agentward/v1")
    out.append("kind: AgentPolicy")
    out.append("metadata:")
    out.append(f"  name: {agent}")
    out.append(f"  owner: {owner}")
    out.append("spec:")
    out.append(f"  subject: {agent}")
    if ttl is not None:
        out.append(f"  expiresAt: \"{ttl}\"")
    out.append("  defaultEffect: Deny")
    out.append("  rules:")
    for key, value in _sorted_grants(manifest):
        out.append(f"    - effect: Allow")
        out.append(f"      actions: [{key}]")
        if value is True:
            out.append("      constraints: {}")
        else:
            lines = _constraints_yaml(value, 6)
            if lines:
                out.extend(lines)
            else:
                out.append("      constraints: {}")
    for key in _sorted_deny(manifest):
        out.append("    - effect: Deny")
        out.append(f"      actions: [{key}]")
    delegations = _sorted_delegations(manifest)
    if delegations:
        out.append("  delegations:")
        for d in delegations:
            out.append(f"    - from: {d.get('from')}")
            out.append(f"      to: {d.get('to')}")
            out.append(f"      purpose: {d.get('purpose')}")
            if d.get("ttl") is not None:
                out.append(f"      expiresAt: \"{d['ttl']}\"")
            child = d.get("narrower_than") if isinstance(d.get("narrower_than"), dict) else {}
            out.append(f"      narrowedActions: [{', '.join(sorted(child))}]")
    out.append("")
    return "\n".join(out)


def export_denylist(manifest, version=__version__) -> str:
    """Platform-neutral deny-list JSON (deterministic, sorted keys)."""
    agent = manifest.get("agent", "unnamed-agent")
    payload = {
        "version": 1,
        "generator": f"manifesto {version}",
        "disclaimer": _DISCLAIMER_COMMON,
        "agent": agent,
        "defaultEffect": "deny",
        "denyAllExceptGranted": True,
        "deny": _sorted_deny(manifest),
        "grants": sorted(_sorted_grants(manifest), key=lambda kv: kv[0]),
        "delegations": [
            {"from": d.get("from"), "to": d.get("to"), "purpose": d.get("purpose"),
             "narrower_than": d.get("narrower_than")
                              if isinstance(d.get("narrower_than"), dict) else {},
             **({"ttl": d["ttl"]} if d.get("ttl") is not None else {})}
            for d in _sorted_delegations(manifest)
        ],
    }
    return json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def export(manifest, target, version=__version__) -> str:
    if target == "agentward":
        return export_agentward(manifest, version)
    if target == "denylist":
        return export_denylist(manifest, version)
    raise ValueError(f"unknown export target {target!r}; choose from {', '.join(TARGETS)}")
